//! Excel's built-in function numbers, as BIFF8 formulas refer to them.
//!
//! A formula token names a function by index, not by name. The table below is
//! the one the format has carried since Excel 97; its numbers, argument counts
//! and operand classes were taken from the `xlrd` Python package and checked
//! against `xlwt`, two independent implementations. They disagree in three
//! places, and each is settled by Excel's own signature: the lower bound of a
//! few variadic functions (`xlrd` allows none, Excel requires one), and
//! `GETPIVOTDATA` and `RTD`, which take up to 30 arguments where `xlrd` stops
//! at 2 and 5. The upper bound matters: a formula over it is not written.
//!
//! Functions added after Excel 2003 have no number: a file stores them by
//! name, as the analysis add-in functions ([`ADD_IN`]) always were.

/// One built-in function.
#[derive(Debug, Clone, Copy)]
pub struct Function {
    /// The number a formula token uses.
    pub index: u16,
    /// The name, as a formula writes it.
    pub name: &'static str,
    /// Fewest arguments.
    pub min: u8,
    /// Most arguments.
    pub max: u8,
    /// What the function returns: `V` a value, `R` a reference, `A` an array.
    pub returns: u8,
    /// The class each argument is expected in, the last repeating for the
    /// rest.
    pub args: &'static str,
}

impl Function {
    /// The class the argument at a position is expected in.
    #[must_use]
    pub fn arg_class(&self, position: usize) -> u8 {
        let bytes = self.args.as_bytes();
        bytes
            .get(position)
            .or_else(|| bytes.last())
            .copied()
            .unwrap_or(b'V')
    }

    /// Whether a formula stores this function with its argument count, which
    /// is every function whose count may vary.
    #[must_use]
    pub const fn is_variadic(&self) -> bool {
        self.min != self.max
    }
}

