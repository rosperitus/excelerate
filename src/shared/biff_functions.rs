/// The name and fixed argument count of a function numbered past the BIFF8
/// table. Only formula text uses these: evaluation knows these functions by
/// name, and their argument classes are not in the table.
#[must_use]
pub fn extended(index: u16) -> Option<(&'static str, Option<u8>)> {
    EXTENDED
        .binary_search_by_key(&index, |(number, _, _)| *number)
        .ok()
        .map(|at| (EXTENDED[at].1, EXTENDED[at].2))
}

/// The numbered function a name stands for, ignoring case.
///
/// Asked on every function call the engine makes, so the table is indexed
/// once rather than walked.
#[must_use]
pub fn by_name(name: &str) -> Option<&'static Function> {
    static INDEX: std::sync::OnceLock<std::collections::HashMap<&'static str, &'static Function>> =
        std::sync::OnceLock::new();
    let index = INDEX.get_or_init(|| FUNCTIONS.iter().map(|f| (f.name, f)).collect());
    match index.get(name) {
        Some(f) => Some(f),
        None if name.bytes().any(|b| b.is_ascii_lowercase()) => {
            index.get(name.to_ascii_uppercase().as_str()).copied()
        }
        None => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_names_are_unique() {
        assert!(FUNCTIONS.windows(2).all(|w| w[0].index < w[1].index));
        assert_eq!(by_index(4).map(|f| f.name), Some("SUM"));
        assert_eq!(by_name("vlookup").map(|f| f.index), Some(102));
        for f in FUNCTIONS {
            assert_eq!(
                by_name(f.name).map(|g| g.index),
                Some(f.index),
                "{}",
                f.name
            );
        }
    }

    #[test]
    fn the_extended_table_is_sorted_and_starts_past_the_first() {
        assert!(EXTENDED.windows(2).all(|w| w[0].0 < w[1].0));
        let first = EXTENDED.first().expect("the table has entries").0;
        assert!(
            FUNCTIONS.iter().all(|f| f.index < first),
            "the two tables must not claim the same number"
        );
        assert_eq!(extended(483).map(|(name, _)| name), Some("AVERAGEIF"));
        assert_eq!(extended(449), Some(("EDATE", Some(2))));
        assert_eq!(extended(1), None, "numbers of the first table are not here");
    }

    /// The names come from another implementation's table, so a typo or a
    /// number off by one would show up as a formula naming a function nobody
    /// has ever heard of. Everything here should be a function this engine
    /// knows, bar the handful that need a world outside the workbook.
    #[cfg(feature = "formulas")]
    #[test]
    fn every_extended_name_is_a_function_this_crate_knows() {
        const OUTSIDE: &[&str] = &[
            "CUBEVALUE",
            "CUBEMEMBER",
            "CUBEMEMBERPROPERTY",
            "CUBERANKEDMEMBER",
            "CUBESET",
            "CUBESETCOUNT",
            "CUBEKPIMEMBER",
        ];
        for &(index, name, _) in EXTENDED {
            assert!(
                crate::formula::functions::is_known(name) || OUTSIDE.contains(&name),
                "{index} names {name:?}, which this crate has never heard of"
            );
        }
    }
}
